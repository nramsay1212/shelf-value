function classify(name) {
  if (OVERRIDE[name]) {
    const [game, type] = OVERRIDE[name];
    return { id: 'sky-' + slug(name), name, game, type, note: NOTES[name] || '' };
  }
  const base = name.split(/ - |\s*\[/)[0].trim();
  const tags = [...name.slice(base.length).matchAll(/[^,\-\[\]]+/g)].map(m => m[0].trim()).filter(Boolean);
  let game = gameIn(name), type;

  if (/portal of power/i.test(name)) type = 'Portals';
  else if (/case\b/i.test(name)) type = 'Accessories';
  else if (/pre-order card|ufo hat/i.test(name)) { type = 'Accessories'; game = game || 'swap'; }
  else if (/adventure pack|level pack|^gryphon park|enchanted elven|^thumpin/i.test(name) || ADVENTURE[base]) {
    type = 'Adventure Packs'; game = game || ADVENTURE[base] || ADVENTURE[name.replace(/^Skylanders.*?: /, '')] || '';
  }
  else if (/triple pack|double pack|battle pack|combo pack|expansion pack|buddy pack|trap pack|starter pack|action pack| & .* - trap team|minis$/i.test(name)) {
    type = 'Packs & Bundles';
    if (/racing action pack/i.test(name)) game = 'super';
    if (/sensei|creation crystal/i.test(name)) game = 'imag';
    if (/mobile|battlegrounds/i.test(name)) game = 'other';
  }
  else if (/trophy/i.test(name)) { type = 'Trophies'; game = 'super'; }
  else if (/mystery chest|chest \[/i.test(name)) { type = 'Magic Items'; game = 'imag'; }
  else if (ELEMENT.test(name) && CRYSTAL_SHAPE.test(name)) { type = 'Creation Crystals'; game = 'imag'; }
  else if (ELEMENT.test(name) && (!game || game === 'trap') && !/bowser|donkey kong|barrel blaster|clown cruiser|spyro/i.test(name) && !VEHICLES.some(v => name.includes(v))) {
    type = 'Traps'; game = 'trap';
  }
  else if (VEHICLES.some(v => base.endsWith(v))) { type = 'Vehicles'; game = 'super'; }
  else if (MINIS.includes(base)) { type = 'Minis & Sidekicks'; game = /sidekicks/i.test(name) ? 'giants' : 'trap'; }

  if (!type) {
    // A figure: work out its game, then whether it's the regular release or a rare variant.
    if (!game && SSA.has(base)) game = 'ssa';
    if (!game && /^(master |sensei )/i.test(name)) game = 'imag';
    if (!game) {
      // "Double Dare Trigger Happy", "Egg Bomber Air Strike": a special version of a known figure.
      const known = NAMES.find(n => n !== name && n.includes(' - ') && base.endsWith(' ' + n.split(' - ')[0]));
      if (known) game = gameIn(known) || (SSA.has(known.split(' - ')[0]) ? 'ssa' : '');
    }
    const rest = tags.filter(t => !GAME_WORDS.some(([re]) => re.test(t)) && !/^adventure$/i.test(t));
    const isMagic = !game && !SSA.has(base);
    if (isMagic) { type = 'Magic Items'; game = 'other'; }
    else if (/eon's elite/i.test(name)) type = 'Variants';
    else if (!rest.length && !/^(?:master |sensei (?:master )?)?(dark|legendary|nitro|heartbreaker|solar flare|candy-coated|hard-boiled|egg bomber|starcast dark|power blue|jingle bell|rock candy|mystical|steel-plated|birthday bash|candy-coated|heartbreaker|solar flare|hard-boiled|egg bomber|quickdraw|thorn horn|king|snow brite)\b/i.test(base)) type = 'Figures';
    else if (rest.length && rest.every(t => /^series [23]$/i.test(t))) type = 'Series 2 & 3';
    else if (rest.length && rest.every(t => /^lightcore$/i.test(t))) type = 'LightCore';
    else if (rest.length && rest.every(t => NEW_VERSION.includes(t.toLowerCase()))) type = 'Figures';
    else type = 'Variants';
  }
  return { id: 'sky-' + slug(name), name, game: game || 'other', type, note: NOTES[name] || '' };
}

const ITEMS = NAMES.map(classify);
